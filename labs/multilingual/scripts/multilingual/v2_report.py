"""Corpus V2 night run: automatic morning report (CPU). Tolerates missing stages (reports them as missing/failed).
Writes ml/results/v2/MORNING_REPORT.md (never overwrites: suffix with a timestamp if present)."""
from __future__ import annotations

import json
import time
from collections import Counter
from pathlib import Path

HOME = Path.home() / "mynah-s2s"
R = HOME / "ml/results/v2"
D = HOME / "ml/data/v2"


def jl(p):
    try:
        return json.load(open(p))
    except Exception:  # noqa: BLE001
        return None


def lines(p):
    try:
        return [json.loads(l) for l in open(p)]
    except Exception:  # noqa: BLE001
        return []


def main():
    out = []
    w = out.append
    w(f"# Corpus V2 night run — automatic report ({time.strftime('%Y-%m-%d %H:%M')})\n")
    w("Generated by `v2_report.py` from the files on the lab box. Numbers only; interpretation goes in experiments.md.\n")
    # jobs
    w("## Jobs\n| job | status | minutes | cause |\n|---|---|---|---|")
    tot = 0.0
    for d in ("done", "failed"):
        for f in sorted((HOME / "queue" / d).glob("ml-v2*.result")):
            r = jl(f) or {}
            m = float(r.get("minutes") or 0)
            if r.get("job", "").startswith("ml-v2-"):
                tot += m
            w(f"| {r.get('job')} | {r.get('status')} | {m:.1f} | {r.get('cause', '')} |")
    pend = sorted(p.name for p in (HOME / "queue/pending").glob("*ml-v2*.job"))
    held = sorted(p.name for p in (HOME / "ml/jobs-held").glob("*ml-v2*.job"))
    w(f"\nGPU minutes (ml-v2-* jobs): **{tot:.0f} / 360**. Pending: {pend or 'none'}. Held (budget stop): {held or 'none'}\n")
    # corpus
    w("## Corpus")
    for name in ("gen_info.json", "translate_info.json", "build_report.json"):
        x = jl(D / name)
        if x:
            x = {k: v for k, v in x.items() if k not in ("leakage_examples",)}
            w(f"- `{name}`: `{json.dumps(x, default=str)[:900]}`")
        else:
            w(f"- `{name}`: missing")
    gen_n = len(lines(D / "families_en.jsonl"))
    tr_n = len(lines(D / "families.jsonl"))
    sp = Counter(f.get("split") for f in lines(D / "families_split.jsonl"))
    ver = jl(R / "manual_spotcheck.json")
    w("\n**Data tiers (the corpus is NOT called clean because it passed automatic filters):**")
    w(f"- generated (Qwen2.5, EN families after JSON parse and dedup): {gen_n}")
    w(f"- automatically filtered (Nano answer check + Nano meaning check + deterministic arithmetic/recall checks + "
      f"leakage): {tr_n} translated families -> splits {dict(sp)}; CV clips -> teacher filter (content-overlap "
      f"heuristic, weak)")
    w(f"- manually verified: {('%d items spot-checked, %s' % (ver['n'], ver['summary'])) if ver else 'none (no manual spot-check recorded)'}")
    w("Caveat: the Nano YES/NO meaning check and the one-content-word CV rule are heuristics, not independent "
      "verification.\n")
    man = lines(D / "train/manifest.jsonl")
    if man:
        c = Counter((r.get("source"), r["lang"], bool(r.get("teacher_only")), r.get("split")) for r in man)
        w(f"- training manifest rows: {len(man)}; by (source, lang, teacher_only, split): "
          f"{sorted(([list(k), v] for k, v in c.items()), key=str)}")
    k = jl(R / "keep_ids.json")
    if k:
        w(f"- teacher filter: kept {len(k['keep'])}, dropped {k['drop_reasons']}")
    # training
    w("\n## Training")
    for name in ("distill/smoke/smoke.json",):
        x = jl(R / name)
        w(f"- smoke: `{json.dumps(x)[:700] if x else 'missing'}`")
    tl = jl(R / "distill/v2/train_log.json")
    if tl:
        best = min((e for e in tl["log"] if "val" in e), key=lambda e: sum(v[0] for v in e["val"].values()))
        w(f"- V2 train: keys {tl.get('n_train_keys')}, val keys {tl.get('n_val_keys')}, init hash {tl.get('init_hash')}, "
          f"train {tl.get('train_s')} s, last step {tl['log'][-1].get('step')}, best step {best['step']} val {best['val']}, "
          f"early stop: {any(e.get('early_stop') for e in tl['log'])}")
    else:
        w("- V2 train: missing")
    # eval
    w("\n## Evaluation (deterministic strict = regex hit, not refusal, not empty)")
    for name in ("score-dev.json", "score-test.json", "score-minds.json", "score-test-lora.json", "score-dev-lora.json"):
        x = jl(R / name)
        if not x:
            w(f"\n### {name}: missing")
            continue
        w(f"\n### {name}")
        langs = sorted({l for v in x["variants"].values() for l in v})
        w("| variant | " + " | ".join(langs) + " |\n|---|" + "---|" * len(langs))
        for v, d in x["variants"].items():
            w(f"| {v} | " + " | ".join(f"{d[l]['strict']}/{d[l]['n']}" if l in d else "—" for l in langs) + " |")
        for pair, res in x["paired"].items():
            w(f"- paired {pair}: " + "; ".join(f"{l} {json.dumps(r)}" for l, r in res.items()))
        w(f"- RNNT WER/CER (vs reference question): `{json.dumps(x['rnnt'])}`")
        w(f"- RNNT identical across dual variants: {x.get('rnnt_identical_across_dual_variants')}")
        w(f"- step latency median of clip p50 (ms per 160 ms chunk): `{json.dumps(x['latency_ms_p50'])}`")
        refu = {v: {l: d[l]["refusal"] for l in d} for v, d in x["variants"].items()}
        w(f"- refusals: `{json.dumps(refu)}`")
        ph = {v: {l: d[l]["by_phenomenon"] for l in d} for v, d in x["variants"].items()}
        w(f"- by phenomenon: `{json.dumps(ph)[:2500]}`")
    for name in ("eval_freeze.json", "noise_audit.json"):
        x = jl(R / name)
        if x:
            x = {k: v for k, v in x.items() if k != "items"}
        w(f"\n- `{name}`: `{json.dumps(x, ensure_ascii=False)[:2500] if x else 'missing'}`")
    for name in ("judge-calibration.json", "judge-test.json", "decision-lora.json"):
        x = jl(R / name)
        if x:
            x = {k: v for k, v in x.items() if k not in ("disagreements", "rows")}
        w(f"\n- `{name}`: `{json.dumps(x)[:1200] if x else 'missing'}`")
    p = R / "MORNING_REPORT.md"
    if p.exists():
        p = R / f"MORNING_REPORT-{int(time.time())}.md"
    p.write_text("\n".join(out) + "\n")
    print(p)


if __name__ == "__main__":
    main()
